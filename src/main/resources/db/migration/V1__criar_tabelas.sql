CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(120) NOT NULL,
    senha_hash VARCHAR(100) NOT NULL,
    perfil VARCHAR(20) NOT NULL,
    matricula VARCHAR(20),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_usuarios_email UNIQUE (email),
    CONSTRAINT ck_usuarios_perfil CHECK (perfil IN ('CLIENTE', 'ATENDENTE', 'COZINHA', 'ADMIN'))
);

CREATE TABLE configuracao_cantina (
    id BIGINT PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    taxa_servico NUMERIC(5, 4) NOT NULL,
    abertura TIME NOT NULL,
    fechamento TIME NOT NULL,
    exigir_horario BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_configuracao_taxa CHECK (taxa_servico >= 0 AND taxa_servico <= 0.3),
    CONSTRAINT ck_configuracao_unica CHECK (id = 1)
);

CREATE TABLE produtos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(60) NOT NULL,
    descricao VARCHAR(200) NOT NULL DEFAULT '',
    preco NUMERIC(10, 2) NOT NULL,
    quantidade_estoque INTEGER NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    versao BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_produtos_preco CHECK (preco > 0),
    CONSTRAINT ck_produtos_estoque CHECK (quantidade_estoque >= 0)
);

CREATE TABLE pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL,
    situacao VARCHAR(30) NOT NULL,
    tipo_pagamento VARCHAR(20),
    valor_total NUMERIC(10, 2),
    troco NUMERIC(10, 2) NOT NULL DEFAULT 0,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    versao BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_pedidos_cliente FOREIGN KEY (cliente_id) REFERENCES usuarios (id)
);

CREATE INDEX idx_pedidos_cliente ON pedidos (cliente_id);
CREATE INDEX idx_pedidos_situacao ON pedidos (situacao);

CREATE TABLE itens_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL,
    produto_id BIGINT NOT NULL,
    quantidade INTEGER NOT NULL,
    preco_unitario NUMERIC(10, 2) NOT NULL,
    CONSTRAINT fk_itens_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos (id) ON DELETE CASCADE,
    CONSTRAINT fk_itens_produto FOREIGN KEY (produto_id) REFERENCES produtos (id),
    CONSTRAINT uk_itens_pedido_produto UNIQUE (pedido_id, produto_id),
    CONSTRAINT ck_itens_quantidade CHECK (quantidade > 0)
);

CREATE TABLE historico_pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL,
    situacao_anterior VARCHAR(30),
    situacao_nova VARCHAR(30) NOT NULL,
    usuario_id BIGINT NOT NULL,
    registrado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_historico_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos (id),
    CONSTRAINT fk_historico_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);

CREATE INDEX idx_historico_pedido ON historico_pedidos (pedido_id);

CREATE TABLE notificacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT,
    perfil_destino VARCHAR(20),
    pedido_id BIGINT NOT NULL,
    mensagem VARCHAR(300) NOT NULL,
    lida BOOLEAN NOT NULL DEFAULT FALSE,
    criada_em TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_notificacoes_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT fk_notificacoes_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos (id),
    CONSTRAINT ck_notificacoes_destino CHECK (usuario_id IS NOT NULL OR perfil_destino IS NOT NULL)
);

CREATE INDEX idx_notificacoes_usuario ON notificacoes (usuario_id);
